"use client";

import { useCallback, useEffect, useState } from "react";
import { useParams } from "next/navigation";
import Link from "next/link";
import { ArrowLeft, Download } from "lucide-react";
import { ProjectShell } from "@/components/layout/ProjectShell";
import { Card, Button, EmptyState, LoadingState, ErrorBanner, StatusBadge, MarkdownView, Modal } from "@/components/ui";
import { useProjectKey } from "@/lib/projects/useProjectKey";
import { useAuth } from "@/lib/auth-context";
import { useRegisterCrumbLabel } from "@/lib/breadcrumbs";
import * as api from "@/lib/recon/api";
import type { ReconReport } from "@/lib/recon/api";

export default function ReconReportDetailPage() {
  const params = useParams<{ id: string; reportId: string }>();
  const projectParam = String(params.id);
  const reportId = String(params.reportId);
  const { key, name } = useProjectKey(projectParam);
  const { can } = useAuth();
  useRegisterCrumbLabel(projectParam, name);
  const canApprove = can("agent:approve");

  const [report, setReport] = useState<ReconReport | null>(null);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [changeModal, setChangeModal] = useState(false);
  const [changeText, setChangeText] = useState("");

  const load = useCallback(async () => {
    try { setReport(await api.getReconReport(reportId)); }
    catch (e) { setErr(e instanceof Error ? e.message : String(e)); }
    finally { setLoading(false); }
  }, [reportId]);
  useEffect(() => { load(); }, [load]);

  async function act(label: string, fn: () => Promise<unknown>) {
    setBusy(label); setErr(null);
    try { await fn(); await load(); }
    catch (e) { setErr(e instanceof Error ? e.message : String(e)); }
    finally { setBusy(null); }
  }

  const reviewable = report && ["generated", "under_review", "changes_requested"].includes(report.status);

  return (
    <ProjectShell projectId={key} projectName={name || "Project"}>
      <Link href={`/projects/${key}/recon/reports`} className="inline-flex items-center gap-1.5 text-[12.5px] text-ink-3 hover:text-ink-1">
        <ArrowLeft className="h-3.5 w-3.5" /> Recon reports
      </Link>
      {err && <ErrorBanner message={err} onDismiss={() => setErr(null)} />}

      {loading ? <LoadingState label="Loading report…" /> : !report ? <EmptyState title="Report not found" /> : (
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-[1fr_280px]">
          <Card title="Reconciliation report" eyebrow={report.report_type} actions={<StatusBadge status={report.status} />}>
            {report.report_markdown ? <MarkdownView text={report.report_markdown} className="hx-md" /> : <p className="text-[13px] text-ink-3">No content.</p>}
          </Card>

          <div className="space-y-6">
            <Card title="Actions">
              <div className="flex flex-col gap-2">
                {report.has_pdf && (
                  <Button size="sm" variant="outline" disabled={!!busy} onClick={() => act("dl", () => api.downloadReconReportPdf(report.id))}>
                    <Download className="h-3.5 w-3.5" /> Download PDF
                  </Button>
                )}
                {canApprove && reviewable && (
                  <Button size="sm" disabled={!!busy} onClick={() => act("approve", () => api.approveReconReport(report.id))}>
                    {busy === "approve" ? "Approving…" : "Approve report"}
                  </Button>
                )}
                {canApprove && reviewable && (
                  <Button size="sm" variant="outline" disabled={!!busy} onClick={() => { setChangeText(""); setChangeModal(true); }}>Request changes</Button>
                )}
                {report.status === "approved" && (
                  <Link href={`/projects/${key}/signoff`} className="text-center text-[12.5px] text-helix-700 hover:underline">Send for sign-off →</Link>
                )}
              </div>
            </Card>
            <Card title="Details">
              <dl className="space-y-2 text-[12.5px]">
                <div className="flex justify-between"><dt className="text-ink-3">Generated by</dt><dd className="text-ink-1">{report.generated_by_agent || "—"}</dd></div>
                <div className="flex justify-between"><dt className="text-ink-3">Approved by</dt><dd className="font-mono text-ink-1">{report.approved_by_user_id ? report.approved_by_user_id.slice(0, 8) : "—"}</dd></div>
                <div className="flex justify-between"><dt className="text-ink-3">Created</dt><dd className="text-ink-1">{report.created_at?.slice(0, 16)?.replace("T", " ") || "—"}</dd></div>
              </dl>
            </Card>
          </div>
        </div>
      )}

      {changeModal && report && (
        <Modal open title="Request changes" onClose={() => setChangeModal(false)} width="md">
          <div className="space-y-3">
            <textarea className="w-full rounded-md border border-hx bg-app px-3 py-2 text-[13px] text-ink-1 focus:border-helix-400 focus:outline-none"
              rows={4} value={changeText} onChange={(e) => setChangeText(e.target.value)} placeholder="What needs to change?" autoFocus />
            <div className="flex justify-end gap-2">
              <Button variant="ghost" onClick={() => setChangeModal(false)}>Cancel</Button>
              <Button disabled={!changeText.trim()} onClick={async () => { setChangeModal(false); await act("changes", () => api.requestReconReportChanges(report.id, changeText.trim())); }}>Submit</Button>
            </div>
          </div>
        </Modal>
      )}
    </ProjectShell>
  );
}
