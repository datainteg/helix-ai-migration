"use client";

import { useState } from "react";
import { Button, Modal, ErrorBanner, StatusBadge } from "@/components/ui";
import * as api from "@/lib/lifecycle/api";
import type { MigrationArtifact } from "@/lib/lifecycle/api";

interface Props {
  artifact: MigrationArtifact;
  versionId: string | null;     // version the reviewer is acting on
  canWrite: boolean;
  canApprove: boolean;
  onChanged: () => void;
}

type Prompt = { action: string; title: string; label: string; required: boolean; run: (t: string) => Promise<unknown> };

function fmt(ts: string | null) {
  if (!ts) return "—";
  const d = new Date(ts);
  return isNaN(d.getTime()) ? ts : d.toLocaleString();
}

export function ArtifactReviewPanel({ artifact, versionId, canWrite, canApprove, onChanged }: Props) {
  const [busy, setBusy] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [prompt, setPrompt] = useState<Prompt | null>(null);
  const [text, setText] = useState("");

  const s = artifact.status;
  const reviewable = ["generated", "under_review", "resubmitted", "changes_requested", "draft"].includes(s);
  const vid = versionId || artifact.current_version_id || undefined;

  async function run(action: string, fn: () => Promise<unknown>) {
    setBusy(action); setErr(null);
    try { await fn(); onChanged(); }
    catch (e) { setErr(e instanceof Error ? e.message : String(e)); }
    finally { setBusy(null); }
  }
  async function submitPrompt() {
    if (!prompt) return;
    if (prompt.required && !text.trim()) { setErr("This field is required."); return; }
    const p = prompt; setPrompt(null);
    await run(p.action, () => p.run(text.trim()));
  }

  return (
    <div className="space-y-4">
      {err && <ErrorBanner message={err} onDismiss={() => setErr(null)} />}

      <dl className="space-y-2 text-[12.5px]">
        <div className="flex items-center justify-between"><dt className="text-ink-3">Status</dt><dd><StatusBadge status={s} /></dd></div>
        <div className="flex items-center justify-between"><dt className="text-ink-3">Type</dt><dd className="text-ink-1">{artifact.artifact_type}</dd></div>
        <div className="flex items-center justify-between"><dt className="text-ink-3">Generated by</dt><dd className="text-ink-1">{artifact.created_by_agent || "—"}</dd></div>
        <div className="flex items-center justify-between"><dt className="text-ink-3">Approved by</dt><dd className="font-mono text-ink-1">{artifact.approved_by_user_id ? artifact.approved_by_user_id.slice(0, 8) : "—"}</dd></div>
        <div className="flex items-center justify-between"><dt className="text-ink-3">Approved at</dt><dd className="text-ink-1">{fmt(artifact.approved_at)}</dd></div>
      </dl>

      <div className="flex flex-wrap gap-2">
        {canWrite && reviewable && s !== "under_review" && (
          <Button variant="outline" size="sm" disabled={!!busy}
            onClick={() => run("submit", () => api.submitArtifactForReview(artifact.id, vid))}>
            Submit for Review
          </Button>
        )}
        {canApprove && reviewable && (
          <Button size="sm" disabled={!!busy} onClick={() => setPrompt({
            action: "approve", title: "Approve artifact", label: "Optional note", required: false,
            run: (t) => api.approveArtifact(artifact.id, vid, t || undefined),
          })}>{busy === "approve" ? "Approving…" : "Approve"}</Button>
        )}
        {canApprove && reviewable && (
          <Button variant="outline" size="sm" disabled={!!busy} onClick={() => setPrompt({
            action: "changes", title: "Request changes", label: "What needs to change?", required: true,
            run: (t) => api.requestArtifactChanges(artifact.id, t, vid),
          })}>Request Changes</Button>
        )}
        {canApprove && reviewable && (
          <Button variant="danger" size="sm" disabled={!!busy} onClick={() => setPrompt({
            action: "reject", title: "Reject artifact", label: "Reason for rejection", required: true,
            run: (t) => api.rejectArtifact(artifact.id, t, vid),
          })}>Reject</Button>
        )}
      </div>

      {prompt && (
        <Modal open title={prompt.title} onClose={() => setPrompt(null)} width="md">
          <div className="space-y-3">
            {err && <ErrorBanner message={err} onDismiss={() => setErr(null)} />}
            <label className="block text-[12px] text-ink-2">{prompt.label}{prompt.required && " *"}</label>
            <textarea className="w-full rounded-md border border-hx bg-app px-3 py-2 text-[13px] text-ink-1 focus:border-helix-400 focus:outline-none"
              rows={4} value={text} onChange={(e) => setText(e.target.value)} autoFocus />
            <div className="flex justify-end gap-2">
              <Button variant="ghost" onClick={() => setPrompt(null)}>Cancel</Button>
              <Button onClick={submitPrompt}>Confirm</Button>
            </div>
          </div>
        </Modal>
      )}
    </div>
  );
}
