"""Align identity-table PKs + FKs to String(36) — drop UUID dialect drift.

DI-C5 from REVIEW_DATA_INTEGRITY.md.

The original migration 25b337c73f7a created organizations/users/roles/
permissions/role_permissions/organization_members PKs as
postgresql.UUID(as_uuid=True). The SQLAlchemy models (via BaseModel)
declare them as String(36). Downstream migrations (e6f7a8b9c0d1
invitations, d5e6f7a8b9c0 org_dek, c4d5e6f7a8b9 password_reset) mix
UUID(as_uuid=False) FKs against models that declare String(36). On
Postgres this causes:
  - implicit casts on every join (kills index usage)
  - hydration drift (UUID objects vs str equality)
  - failure modes on strict FK validators when types disagree

The codebase chose String(36) as the model standard (BaseModel +
every non-identity table); the source of truth is the model. This
migration aligns the DB to match.

Strategy:
  - On Postgres: ALTER COLUMN ... TYPE VARCHAR(36) USING ...::text for
    every PK/FK that's currently UUID. Existing data is preserved
    (UUIDs cast cleanly to 36-char hyphenated text).
  - On SQLite: no-op (Base.metadata.create_all builds VARCHAR already).

Tables/columns altered:
  organizations.id
  users.id
  permissions.id
  roles.id, roles.organization_id
  role_permissions.id, role_permissions.role_id, role_permissions.permission_id
  organization_members.id, organization_members.organization_id,
    organization_members.user_id, organization_members.role_id
  password_reset_tokens.id, password_reset_tokens.user_id
  org_data_encryption_keys.id, org_data_encryption_keys.organization_id
  org_invitations.organization_id, org_invitations.invited_by_user_id,
    org_invitations.role_id

Foreign-key constraints are dropped and re-added so the dependent
columns can be altered without Postgres rejecting the type change.

Revision ID: 8f881cfc333e
Revises: eadec18c9cfc
Create Date: 2026-05-26
"""

