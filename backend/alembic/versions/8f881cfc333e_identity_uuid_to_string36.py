def _table_exists(bind, name: str) -> bool:
    insp = sa.inspect(bind)
    return name in insp.get_table_names()


def _column_is_uuid(bind, table: str, column: str) -> bool:
    """Best-effort check — returns True when the column's stored type
    contains 'uuid' (Postgres native UUID), False otherwise."""
    if not _table_exists(bind, table):
        return False
    insp = sa.inspect(bind)
    for col in insp.get_columns(table):
        if col["name"] == column:
            t = str(col["type"]).lower()
            return "uuid" in t
    return False


def upgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        # SQLite/others already use TEXT (no UUID dialect type).
        return

    # Step 1: drop FK constraints on dependent columns so we can ALTER
    # PKs without "type mismatch" rejections. Postgres will let us
    # ALTER COLUMN TYPE on columns referenced by FKs but only when the
    # referenced column is altered first AND types match. Easiest:
    # drop FKs, alter types, recreate FKs.
    #
    # We discover FK names via reflection so we don't depend on
    # autogenerated constraint name conventions across alembic versions.
    insp = sa.inspect(bind)
    fk_drops: list[tuple[str, str]] = []  # (table, fk_name)
    fk_recreates: list[dict] = []         # info needed to recreate

    fk_owner_tables = [
        "roles",
        "role_permissions",
        "organization_members",
        "password_reset_tokens",
        "org_data_encryption_keys",
        "org_invitations",
    ]
    for tbl in fk_owner_tables:
        if not _table_exists(bind, tbl):
            continue
        for fk in insp.get_foreign_keys(tbl):
            if not fk.get("name"):
                continue
            fk_drops.append((tbl, fk["name"]))
            fk_recreates.append({
                "src_table": tbl,
                "src_columns": list(fk["constrained_columns"]),
                "ref_table": fk["referred_table"],
                "ref_columns": list(fk["referred_columns"]),
                "name": fk["name"],
                "ondelete": (fk.get("options") or {}).get("ondelete"),
            })

    for tbl, name in fk_drops:
        op.execute(f'ALTER TABLE {tbl} DROP CONSTRAINT IF EXISTS "{name}"')

    # Step 2: ALTER each column to VARCHAR(36) using a text cast that
    # preserves the UUID's hyphenated string representation.
    for table, column in _PK_FK_COLUMNS:
        if not _column_is_uuid(bind, table, column):
            continue
        op.execute(
            f'ALTER TABLE {table} '
            f'ALTER COLUMN {column} TYPE VARCHAR(36) USING {column}::text'
        )

    # Step 3: recreate FKs with the original names + ondelete behaviour.
    for fk in fk_recreates:
        # Skip if either side no longer exists (defensive).
        if not _table_exists(bind, fk["src_table"]) or not _table_exists(bind, fk["ref_table"]):
            continue
        kwargs: dict = {}
        if fk["ondelete"]:
            kwargs["ondelete"] = fk["ondelete"]
        op.create_foreign_key(
            fk["name"],
            fk["src_table"],
            fk["ref_table"],
            fk["src_columns"],
            fk["ref_columns"],
            **kwargs,
        )


def downgrade() -> None:
    # Re-creating the UUID-typed columns would require parsing every
    # value back; not worth the complexity for a downgrade path that
    # would never be used in practice. Document and no-op.
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        return
    # Intentional no-op. To revert, restore from backup taken before
    # 8f881cfc333e was applied.
