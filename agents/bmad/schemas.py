"""Lightweight metadata schemas for BMAD agent outputs.

BMAD agents produce free-form markdown artifacts as their primary deliverable
(PRDs, architecture docs, story files, etc.). These markdown files live in
`planning_artifacts/{project_id}/{agent_code}/...md` and serve as the source
of truth for downstream agents.

The Pydantic models below describe the COMPACT METADATA we extract from each
markdown artifact for:
  - dashboard/UI display
  - `WorkflowStep.parsed_output_json` persistence
  - downstream agents that only need a quick summary, not the full doc

A model maps 1:1 to a BMAD agent. Fields are deliberately minimal — anything
richer should live in the markdown body and be retrieved via
`agents.runtime.artifact_store.read_artifact()`.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


# ── Shared sub-models ────────────────────────────────────────────────


class RiskItem(BaseModel):
    title: str
    severity: Literal["low", "medium", "high", "critical"]
    impact: str
    mitigation: str


class ArtifactRef(BaseModel):
    """Pointer to a markdown artifact this agent wrote."""

    filename: str
    path: str  # absolute path on disk
    summary: str = ""


# ── Per-agent metadata models ────────────────────────────────────────


class AnalystOutput(BaseModel):
    """Mary (bmad-agent-analyst) — Analysis phase."""

    summary: str
    business_goals: list[str] = Field(default_factory=list)
    open_questions: list[str] = Field(default_factory=list)
    assumptions: list[str] = Field(default_factory=list)
    risks: list[RiskItem] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class PMOutput(BaseModel):
    """John (bmad-agent-pm) — PRD creation."""

    summary: str
    user_stories: list[str] = Field(default_factory=list)
    success_metrics: list[str] = Field(default_factory=list)
    risks: list[RiskItem] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class UXDesignerOutput(BaseModel):
    """Sally (bmad-agent-ux-designer) — UX flows."""

    summary: str
    flows: list[str] = Field(default_factory=list)
    components: list[str] = Field(default_factory=list)
    risks: list[RiskItem] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class ArchitectOutput(BaseModel):
    """Winston (bmad-agent-architect) — architecture + epics & stories."""

    summary: str
    source_systems: list[str] = Field(default_factory=list)
    target_systems: list[str] = Field(default_factory=list)
    integration_points: list[str] = Field(default_factory=list)
    dependencies: list[str] = Field(default_factory=list)
    risks: list[RiskItem] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class ApprovalGateOutput(BaseModel):
    approval_required: bool
    approval_reason: str
    next_step: str


class DevOutput(BaseModel):
    """Amelia (bmad-agent-dev) — story implementation + code review."""

    summary: str
    story_id: str = ""
    acceptance_criteria_met: list[str] = Field(default_factory=list)
    files_changed: list[str] = Field(default_factory=list)
    tests_added: list[str] = Field(default_factory=list)
    risks: list[RiskItem] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class QAOutput(BaseModel):
    """E2E tests generated by Amelia invoking bmad-qa-generate-e2e-tests."""

    summary: str
    test_cases: list[str] = Field(default_factory=list)
    coverage_targets: list[str] = Field(default_factory=list)
    risks: list[RiskItem] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class CodeReviewOutput(BaseModel):
    """Amelia invoking bmad-code-review."""

    summary: str
    findings: list[str] = Field(default_factory=list)
    blocking_issues: list[str] = Field(default_factory=list)
    sign_off: Literal["approved", "needs_revision", "blocked"] = "needs_revision"
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class TechWriterOutput(BaseModel):
    """Paige (bmad-agent-tech-writer) — final docs."""

    summary: str
    documents: list[str] = Field(default_factory=list)
    diagrams: list[str] = Field(default_factory=list)
    artifacts: list[ArtifactRef] = Field(default_factory=list)


class BMADFinalOutput(BaseModel):
    """Aggregate output of a completed BMAD workflow."""

    analyst: AnalystOutput | None = None
    pm: PMOutput | None = None
    ux_designer: UXDesignerOutput | None = None
    architect: ArchitectOutput | None = None
    approval_gate: ApprovalGateOutput | None = None
    dev: DevOutput | None = None
    qa: QAOutput | None = None
    code_review: CodeReviewOutput | None = None
    tech_writer: TechWriterOutput | None = None
    status: str


# ── Map agent code → output model (used by nodes + tests) ────────────


AGENT_OUTPUT_MODELS: dict[str, type[BaseModel]] = {
    "bmad-agent-analyst": AnalystOutput,
    "bmad-agent-pm": PMOutput,
    "bmad-agent-ux-designer": UXDesignerOutput,
    "bmad-agent-architect": ArchitectOutput,
    "bmad-agent-dev": DevOutput,
    "bmad-agent-tech-writer": TechWriterOutput,
}


